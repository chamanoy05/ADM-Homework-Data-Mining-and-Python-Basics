def super_digit(n: str, k: int) -> int:
    """
    Calculates the super digit of a number string 'n' repeated 'k' times
    using recursion.
    """
    # Sum the digits of string n first, then scale by k
    # This prevents storing huge strings in memory
    initial_sum = sum(int(digit) for digit in n) * k

    def recursive_super_digit(val: int) -> int:
        if val < 10:
            return val
        next_sum = sum(int(digit) for digit in str(val))
        return recursive_super_digit(next_sum)

    return recursive_super_digit(initial_sum)

if __name__ == '__main__':
    # Input format: Space-separated string n and integer k
    data = input("Enter n and k (e.g. 9875 4): ").split()
    n_val = data[0]
    k_val = int(data[1])

    result = super_digit(n_val, k_val)
    print(f"Super digit of '{n_val}' repeated {k_val} times:", result)

