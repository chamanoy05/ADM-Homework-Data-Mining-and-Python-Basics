def insertion_sort_1(n: int, arr: list) -> None:
    """
    Inserts the last element into its sorted position,
    printing the array array after every shift.
    """
    target = arr[-1]
    i = n - 2

    while i >= 0 and arr[i] > target:
        arr[i + 1] = arr[i]
        print(*arr)
        i -= 1

    arr[i + 1] = target
    print(*arr)

if __name__ == '__main__':
    n = int(input("Enter array size: "))
    arr = list(map(int, input("Enter array elements: ").split()))

    print("\nSorting Steps:")
    insertion_sort_1(n, arr)

"""arr[i + 1] = arr[i]: Shifts the larger element one index to the right while making space for target. print(*arr) displays the intermediate array state.

### Insertion Sort Part 2
"""

def insertion_sort_2(n: int, arr: list) -> None:
    """
    Performs full insertion sort on the list, printing
    the array state after each element is inserted.
    """
    for i in range(1, n):
        key = arr[i]
        j = i - 1

        while j >= 0 and arr[j] > key:
            arr[j + 1] = arr[j]
            j -= 1

        arr[j + 1] = key
        print(*arr)

if __name__ == '__main__':
    n = int(input("Enter array size: "))
    arr = list(map(int, input("Enter array elements: ").split()))

    print("\nArray state after each pass:")
    insertion_sort_2(n, arr)

"""for i in range(1, n):: Iterates through the array starting from index 1, inserting each element into the sorted sub-array arr[0...i-1]. print(*arr) outputs the progress after each complete insertion step."""