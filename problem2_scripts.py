def kangaroo(x1, v1, x2, v2):
    """
    Determines whether two kangaroos starting at positions x1 and x2
    moving at speeds v1 and v2 will land on the exact same location
    at the exact same time.
    """
    if v1 <= v2:
        return "NO"

    if (x2 - x1) % (v1 - v2) == 0:
        return "YES"
    return "NO"

if __name__ == '__main__':
    # Input format: Space-separated integers x1 v1 x2 v2
    data = input("Enter x1 v1 x2 v2: ").split()
    x1, v1, x2, v2 = map(int, data)

    result = kangaroo(x1, v1, x2, v2)
    print("Will they meet?:", result)

