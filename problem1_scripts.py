def merge_the_tools(string, k):
    """
    Splits string into contiguous substrings of length k,
    removes duplicate characters while preserving order, and prints each.
    """
    # Step through string in chunks of size k
    for i in range(0, len(string), k):
        sub = string[i:i+k]
        seen = []
        for char in sub:
            if char not in seen:
                seen.append(char)
        print("".join(seen))

