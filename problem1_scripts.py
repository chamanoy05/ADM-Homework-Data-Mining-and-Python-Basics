from collections import deque

def execute_deque_operations(operations):
    """
    Executes a series of append, appendleft, pop, and popleft
    operations on a double-ended queue (deque).
    """
    d = deque()

    for op in operations:
        parts = op.split()
        method = parts[0]

        if method == 'append':
            d.append(parts[1])
        elif method == 'appendleft':
            d.appendleft(parts[1])
        elif method == 'pop':
            d.pop()
        elif method == 'popleft':
            d.popleft()

    return list(d)

