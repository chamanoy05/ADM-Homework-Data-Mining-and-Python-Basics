def can_stack_cubes(blocks):
    """
    Determines if cubes can be stacked such that every upper cube
    has a side length less than or equal to the cube below it.
    """
    d = deque(blocks)
    last_stacked = float('inf')

    while d:
        if d[0] >= d[-1]:
            chosen = d.popleft()
        else:
            chosen = d.pop()

        if chosen > last_stacked:
            return "No"

        last_stacked = chosen

    return "Yes"

