def print_formatted(number):
    """
    Prints decimal, octal, hexadecimal, and binary representations
    for numbers from 1 to `number`, padded to match the width
    of the binary representation of `number`.
    """
    # Calculate padding width based on binary representation length
    width = len(bin(number)[2:])

    for i in range(1, number + 1):
        dec = str(i)
        octal = oct(i)[2:]
        hexa = hex(i)[2:].upper()
        binary = bin(i)[2:]

        # Print space-padded values right-aligned
        print(f"{dec.rjust(width)} {octal.rjust(width)} {hexa.rjust(width)} {binary.rjust(width)}")

if __name__ == '__main__':
    # Interactive input for Google Colab testing
    n = int(input("Enter maximum number (n): "))
    print_formatted(n)

